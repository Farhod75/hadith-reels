#!/usr/bin/env node
/**
 * .claude/hooks/session-start.js  (v2 - P334 addendum)
 *
 * Puts PATTERN_INDEX.md into the session's opening context, in parts.
 *
 * WHY PARTS. Claude Code caps a hook's plain stdout at 10,000 characters. Over
 * the cap it saves the output to a file and passes only the path and a
 * 2,000-character preview, and does not ask Claude to read the file
 * (code.claude.com/docs/en/hooks, "JSON output" and "Add context for Claude").
 * v1 printed 21,338 characters in one go - so all but the header would have
 * been filed where nothing reads it, the exact failure P334 was fixing.
 * The same page says each hook's output is measured on its own, even when
 * several hooks run for the same event - so .claude/settings.json declares one
 * handler per part, and this script prints only the part it is asked for.
 *
 *   node .claude/hooks/session-start.js 1     print part 1 (prints nothing if
 *                                             there is no such part)
 *   node .claude/hooks/session-start.js --plan
 *                                             print how many parts the index
 *                                             needs and each part's size;
 *                                             audit-docs.py compares that with
 *                                             the handlers settings.json declares
 *
 * The slicing lives HERE only. audit-docs.py asks this script rather than
 * re-deriving the rule (P270).
 *
 * Text is written as facts, not commands: the docs note that text framed as
 * out-of-band instructions can trip prompt-injection defences, so it would be
 * surfaced rather than used.
 *
 * Output must not begin with '{' or it is parsed as JSON. Node, not cat/head:
 * this machine is Windows (P334).
 */
const fs = require('fs');
const path = require('path');

const ROOT = process.cwd();
const INDEX = path.join(ROOT, 'PATTERN_INDEX.md');
const UPSKILL = path.join(ROOT, 'self_upskilling.md');
const LIMIT = 9000;          // cap is 10,000; keep margin for the part header

function upskillLine() {
  try {
    const su = fs.readFileSync(UPSKILL, 'utf-8');
    const m = su.match(/\*\*Next due:\*\*\s*(\d{4}-\d{2}-\d{2})/);
    if (!m) return 'self_upskilling.md has no Next due date.';
    const due = new Date(m[1] + 'T00:00:00Z');
    const today = new Date(new Date().toISOString().slice(0, 10) + 'T00:00:00Z');
    const days = Math.round((due - today) / 86400000);
    if (days < 0) {
      return 'The self_upskilling.md tool review is ' + (-days) + ' day(s) OVERDUE (due '
        + m[1] + '); audit-docs.py fails every push until it is run (P198, P332).';
    }
    return 'The weekly tool review in self_upskilling.md is due ' + m[1]
      + ' (' + days + ' day(s) from today).';
  } catch (e) {
    return 'self_upskilling.md could not be read: ' + e.message;
  }
}

function buildParts() {
  let raw;
  try {
    raw = fs.readFileSync(INDEX, 'utf-8').replace(/\r\n/g, '\n');
  } catch (e) {
    return ['PATTERN_INDEX.md could not be read (' + e.message + '). '
      + 'It is regenerated by `python scripts/build-pattern-index.py`.'];
  }
  const cut = raw.indexOf('## By number');
  const head = (cut > 0 ? raw.slice(0, cut) : raw).trimEnd();
  const rows = cut > 0 ? raw.slice(cut).split('\n') : [];

  const first = [
    'hadith-reels session context: the pattern index, in parts.',
    '',
    head,
    '',
    'The patterns listed under "By file" are every pattern that has touched',
    'that script. Each title is a pointer; the lesson is the full text at',
    '`## PATTERN <n>` in fix_patterns.md.',
    '',
    upskillLine(),
  ].join('\n');

  const parts = [first];
  let cur = [];
  let len = 0;
  for (const line of rows) {
    if (len + line.length + 1 > LIMIT && cur.length) {
      parts.push(cur.join('\n'));
      cur = [];
      len = 0;
    }
    cur.push(line);
    len += line.length + 1;
  }
  if (cur.length && cur.join('').trim()) parts.push(cur.join('\n'));
  return parts;
}

const parts = buildParts();
const arg = process.argv[2];

if (arg === '--plan') {
  process.stdout.write('parts=' + parts.length + '\n');
  parts.forEach((p, i) => {
    process.stdout.write('part ' + (i + 1) + ' chars=' + (p.length + 40) + '\n');
  });
  process.exit(0);
}

const k = parseInt(arg || '1', 10);
if (!(k >= 1) || k > parts.length) process.exit(0);
process.stdout.write('PATTERN_INDEX part ' + k + '/' + parts.length + '\n'
  + parts[k - 1].trimEnd() + '\n');
